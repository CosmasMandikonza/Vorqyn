/* Orchestration                                                       */
/* ------------------------------------------------------------------ */
function main() {
  fs.mkdirSync(MODELS_DIR, { recursive: true });
  fs.mkdirSync(PREVIEWS_DIR, { recursive: true });

  const outputs = [];

  const run = (name, buildFn) => {
    const scene = new Scene();
    buildFn(scene);
    const { gltf, bin } = buildGltfJson(scene, name);
    const bytes = writeGlb(path.join(MODELS_DIR, name + ".glb"), gltf, bin);
    const stats = gltfStats(scene);
    const bounds = enuBounds(scene);
    outputs.push({ name: name + ".glb", bytes, stats, bounds });
    console.log(
      `[gen] ${name}.glb  ${(bytes / 1024).toFixed(1)} KiB  tris=${stats.triangles}  verts=${stats.vertices}  prims=${stats.primitives}  ENU bounds=[${bounds.min.map((v) => v.toFixed(1)).join(",")}] .. [${bounds.max.map((v) => v.toFixed(1)).join(",")}]`
    );
    return { stats, bounds };
  };

  const high = run("port-world-high", (s) => buildPort(s, "high"));
  const low = run("port-world-low", (s) => buildPort(s, "low"));
  run("drone-ref", buildDrone);
  run("rover-ref", buildRover);
  run("rov-ref", buildRov);

  /* budget enforcement at generation time */
  if (high.stats.triangles > WORLD.lod.high.max_triangles) throw new Error(`high LOD exceeds triangle budget: ${high.stats.triangles}`);
  if (low.stats.triangles > WORLD.lod.low.max_triangles) throw new Error(`low LOD exceeds triangle budget: ${low.stats.triangles}`);

  /* world.json */
  const worldPath = path.join(OUT, "world.json");
  fs.writeFileSync(worldPath, JSON.stringify(WORLD, null, 2) + "\n");

  /* plan-view.svg */
  fs.writeFileSync(path.join(PREVIEWS_DIR, "plan-view.svg"), planViewSvg() + "\n");

  /* manifest */
  const manifest = {
    schema: "vorqyn.port-world.manifest/1",
    world_id: WORLD.world_id,
    generated_by: {
      tool: "assets/port-world/tools/generate.mjs",
      tool_sha256: crypto.createHash("sha256").update(fs.readFileSync(THIS_FILE)).digest("hex"),
      node: NODE_VERSION,
      deterministic: true,
      note: "regenerate with: node tools/generate.mjs (from assets/port-world/)",
    },
    generated_at_utc: new Date().toISOString(),
    files: [],
  };
  const rel = (p) => path.relative(OUT, p).split(path.sep).join("/");
  for (const o of outputs) {
    const p = path.join(MODELS_DIR, o.name);
    const data = fs.readFileSync(p);
    manifest.files.push({
      path: rel(p),
      bytes: data.length,
      sha256: crypto.createHash("sha256").update(data).digest("hex"),
      gltf: {
        triangles: o.stats.triangles,
        vertices: o.stats.vertices,
        primitives: o.stats.primitives,
        bounds_enu_m: { min: o.bounds.min, max: o.bounds.max },
      },
    });
  }
  for (const extra of [rel(worldPath), rel(path.join(PREVIEWS_DIR, "plan-view.svg"))]) {
    const p = path.join(OUT, extra);
    const data = fs.readFileSync(p);
    manifest.files.push({
      path: extra,
      bytes: data.length,
      sha256: crypto.createHash("sha256").update(data).digest("hex"),
    });
  }
  fs.writeFileSync(path.join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");

  console.log(`[gen] world.json, plan-view.svg, manifest.json written.`);
  console.log(`[gen] budgets: high=${high.stats.triangles}/${WORLD.lod.high.max_triangles}  low=${low.stats.triangles}/${WORLD.lod.low.max_triangles}`);
}

main();
