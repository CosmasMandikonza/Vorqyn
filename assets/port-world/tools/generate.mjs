function seabedHeight(x, y) {
  let z = -12
    + 0.8 * Math.sin(x * 0.021) * Math.cos(y * 0.017)
    - 1.5 * Math.max(0, (-60 - y) / 140);
  return Math.min(-11.2, Math.max(-13.8, z));
}

