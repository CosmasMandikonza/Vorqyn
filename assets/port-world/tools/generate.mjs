const D2R = Math.PI / 180;

function basisFromEuler(yawDeg, pitchDeg, rollDeg) {
  // Extrinsic ZYX: R = Rz(yaw) * Ry(pitch) * Rx(roll), applied to local axes.
  const cy = Math.cos(yawDeg * D2R), sy = Math.sin(yawDeg * D2R);
  const cp = Math.cos(pitchDeg * D2R), sp = Math.sin(pitchDeg * D2R);
  const cr = Math.cos(rollDeg * D2R), sr = Math.sin(rollDeg * D2R);
  // Columns are local axes u,v,w in ENU.
  const u = [cy * cp, sy * cp, -sp];
  const v = [
    cy * sp * sr - sy * cr,
    sy * sp * sr + cy * cr,
    cp * sr,
  ];
  const w = [
    cy * sp * cr + sy * sr,
    sy * sp * cr - cy * sr,
    cp * cr,
  ];
  return [u, v, w];
}

class Scene {
  constructor() {
    this.byMat = new Map(); // materialName -> {pos:[], nrm:[], col:[], idx:[], vcount}
  }
  acc(mat) {
    let a = this.byMat.get(mat);
    if (!a) { a = { pos: [], nrm: [], col: [], idx: [], vcount: 0 }; this.byMat.set(mat, a); }
    return a;
  }
  /**
   * Add a quad with intended outward normal; winding auto-corrected.
   * corners = [p0,p1,p2,p3] in order around the quad.
   */
  quad(mat, corners, normal, color) {
    const a = this.acc(mat);
    const n = normal;
    const e1 = [corners[1][0] - corners[0][0], corners[1][1] - corners[0][1], corners[1][2] - corners[0][2]];
    const e2 = [corners[2][0] - corners[0][0], corners[2][1] - corners[0][1], corners[2][2] - corners[0][2]];
    const cross = [
      e1[1] * e2[2] - e1[2] * e2[1],
      e1[2] * e2[0] - e1[0] * e2[2],
      e1[0] * e2[1] - e1[1] * e2[0],
    ];
    const dot = cross[0] * n[0] + cross[1] * n[1] + cross[2] * n[2];
    let c = corners;
    if (dot < 0) c = [corners[0], corners[3], corners[2], corners[1]];
    const base = a.vcount;
    for (let i = 0; i < 4; i++) {
      a.pos.push(c[i][0], c[i][1], c[i][2]);
      a.nrm.push(n[0], n[1], n[2]);
      if (color) a.col.push(
        Math.round(color[0] * 255), Math.round(color[1] * 255),
        Math.round(color[2] * 255), 255
      );
    }
    a.idx.push(base, base + 1, base + 2, base, base + 2, base + 3);
    a.vcount += 4;
  }
  /** Oriented box: center, dims along basis axes, euler orientation (deg). */
  box(mat, center, dims, opts = {}) {
    const [u, v, w] = basisFromEuler(opts.yaw || 0, opts.pitch || 0, opts.roll || 0);
    const hx = dims[0] / 2, hy = dims[1] / 2, hz = dims[2] / 2;
    const color = opts.color;
    const defs = [
      { s: 1, ax: 0 }, { s: -1, ax: 0 },
      { s: 1, ax: 1 }, { s: -1, ax: 1 },
      { s: 1, ax: 2 }, { s: -1, ax: 2 },
    ];
    const half = [hx, hy, hz];
    const axes = [u, v, w];
    for (const d of defs) {
      const nAx = axes[d.ax];
      const nrm = [d.s * nAx[0], d.s * nAx[1], d.s * nAx[2]];
      const t1ax = (d.ax + 1) % 3, t2ax = (d.ax + 2) % 3;
      // Tangent pairs carry their half-extent so direction and scale can never
      // desync when the right-handedness swap below reorders them.
      let t1 = { v: axes[t1ax], h: half[t1ax] };
      let t2 = { v: axes[t2ax], h: half[t2ax] };
      const tri =
        t1.v[0] * (t2.v[1] * nrm[2] - t2.v[2] * nrm[1]) +
        t1.v[1] * (t2.v[2] * nrm[0] - t2.v[0] * nrm[2]) +
        t1.v[2] * (t2.v[0] * nrm[1] - t2.v[1] * nrm[0]);
      if (tri < 0) { const tmp = t1; t1 = t2; t2 = tmp; }
      const pt = (a1, a2) => [
        center[0] + d.s * half[d.ax] * nAx[0] + a1 * t1.h * t1.v[0] + a2 * t2.h * t2.v[0],
        center[1] + d.s * half[d.ax] * nAx[1] + a1 * t1.h * t1.v[1] + a2 * t2.h * t2.v[1],
        center[2] + d.s * half[d.ax] * nAx[2] + a1 * t1.h * t1.v[2] + a2 * t2.h * t2.v[2],
      ];
      const corners = [pt(-1, -1), pt(1, -1), pt(1, 1), pt(-1, 1)];
      this.quad(mat, corners, nrm, color);
    }
  }
  /** Cylinder from p0 to p1 (ENU), radius r, segs sides, optional cap color. */
  cylinder(mat, p0, p1, r, segs, color) {
    this.acc(mat);
    const ax = [p1[0] - p0[0], p1[1] - p0[1], p1[2] - p0[2]];
    const len = Math.hypot(ax[0], ax[1], ax[2]) || 1;
    const n0 = [ax[0] / len, ax[1] / len, ax[2] / len];
    // orthonormal tangents
    let t1 = Math.abs(n0[2]) < 0.9 ? [0, 0, 1] : [1, 0, 0];
    let t2 = [
      n0[1] * t1[2] - n0[2] * t1[1],
      n0[2] * t1[0] - n0[0] * t1[2],
      n0[0] * t1[1] - n0[1] * t1[0],
    ];
    const t2l = Math.hypot(t2[0], t2[1], t2[2]) || 1;
    t2 = [t2[0] / t2l, t2[1] / t2l, t2[2] / t2l];
    t1 = [
      t2[1] * n0[2] - t2[2] * n0[1],
      t2[2] * n0[0] - t2[0] * n0[2],
      t2[0] * n0[1] - t2[1] * n0[0],
    ];
    const ringPts = (p, sign) => {
      const pts = [];
      for (let i = 0; i < segs; i++) {
        const th = (i / segs) * Math.PI * 2;
        const rx = Math.cos(th) * t1[0] + Math.sin(th) * t2[0];
        const ry = Math.cos(th) * t1[1] + Math.sin(th) * t2[1];
        const rz = Math.cos(th) * t1[2] + Math.sin(th) * t2[2];
        pts.push({
          p: [p[0] + r * rx, p[1] + r * ry, p[2] + r * rz],
          n: [sign * rx, sign * ry, sign * rz],
        });
      }
      return pts;
    };
    const b = ringPts(p0, 1), t = ringPts(p1, 1);
    for (let i = 0; i < segs; i++) {
      const j = (i + 1) % segs;
      // side quad b_i, b_j, t_j, t_i with outward radial normal
      this.quad(mat, [b[i].p, b[j].p, t[j].p, t[i].p], b[i].n, color);
    }
    // caps (fan, normals along +/- axis)
    const capC = (pts, center, nrmCap) => {
      const bb = this.acc(mat);
      const baseCap = bb.vcount;
      bb.pos.push(center[0], center[1], center[2]);
      bb.nrm.push(nrmCap[0], nrmCap[1], nrmCap[2]);
      if (color) bb.col.push(
        Math.round(color[0] * 255), Math.round(color[1] * 255),
        Math.round(color[2] * 255), 255
      );
      bb.vcount += 1;
      const ringBase = bb.vcount;
      for (const q of pts) {
        bb.pos.push(q.p[0], q.p[1], q.p[2]);
        bb.nrm.push(nrmCap[0], nrmCap[1], nrmCap[2]);
        if (color) bb.col.push(
          Math.round(color[0] * 255), Math.round(color[1] * 255),
          Math.round(color[2] * 255), 255
        );
        bb.vcount += 1;
      }
      for (let i = 0; i < segs; i++) {
        const j = (i + 1) % segs;
        // triangle: center, ring_i, ring_j — orient so normal matches nrmCap
        const A = center, B = pts[i].p, C = pts[j].p;
        const e1 = [B[0] - A[0], B[1] - A[1], B[2] - A[2]];
        const e2 = [C[0] - A[0], C[1] - A[1], C[2] - A[2]];
        const cx = e1[1] * e2[2] - e1[2] * e2[1];
        const cy2 = e1[2] * e2[0] - e1[0] * e2[2];
        const cz = e1[0] * e2[1] - e1[1] * e2[0];
        const d = cx * nrmCap[0] + cy2 * nrmCap[1] + cz * nrmCap[2];
        if (d >= 0) bb.idx.push(baseCap, ringBase + i, ringBase + j);
        else bb.idx.push(baseCap, ringBase + j, ringBase + i);
      }
    };
    capC(b, p0, [-n0[0], -n0[1], -n0[2]]);
    capC(t, p1, n0);
  }
  /** Flat grid patch in the x/y plane at height fn(x,y). */
  grid(mat, x0, x1, y0, y1, nx, ny, fn, color) {
    for (let i = 0; i < nx; i++) {
      for (let j = 0; j < ny; j++) {
        const xa = x0 + ((x1 - x0) * i) / nx, xb = x0 + ((x1 - x0) * (i + 1)) / nx;
        const ya = y0 + ((y1 - y0) * j) / ny, yb = y0 + ((y1 - y0) * (j + 1)) / ny;
        const z00 = fn(xa, ya), z10 = fn(xb, ya), z11 = fn(xb, yb), z01 = fn(xa, yb);
        const e1 = [xb - xa, 0, z10 - z00];
        const e2 = [0, yb - ya, z01 - z00];
        let n = [
          e1[1] * e2[2] - e1[2] * e2[1],
          e1[2] * e2[0] - e1[0] * e2[2],
          e1[0] * e2[1] - e1[1] * e2[0],
        ];
        const nl = Math.hypot(n[0], n[1], n[2]) || 1;
        n = [n[0] / nl, n[1] / nl, n[2] / nl];
        if (n[2] < 0) n = [-n[0], -n[1], -n[2]];
        this.quad(mat, [
          [xa, ya, z00], [xb, ya, z10], [xb, yb, z11], [xa, yb, z01],
        ], n, color);
      }
    }
  }
  /** Simple horizontal quad at height z with up normal. */
  flatQuad(mat, x0, x1, y0, y1, z, color) {
    this.quad(mat, [
      [x0, y0, z], [x1, y0, z], [x1, y1, z], [x0, y1, z],
    ], [0, 0, 1], color);
  }
  tri(mat, A, B, C, n, color) {
    const a = this.acc(mat);
    const base = a.vcount;
    a.pos.push(A[0], A[1], A[2], B[0], B[1], B[2], C[0], C[1], C[2]);
    for (let i = 0; i < 3; i++) a.nrm.push(n[0], n[1], n[2]);
    if (color) for (let i = 0; i < 3; i++) a.col.push(
      Math.round(color[0] * 255), Math.round(color[1] * 255),
      Math.round(color[2] * 255), 255
    );
    a.idx.push(base, base + 1, base + 2);
    a.vcount += 3;
  }
}

