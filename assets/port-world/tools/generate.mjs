function planViewSvg() {
  const S = 1.6; // px per meter
  const W = Math.ceil(640 * S), H = Math.ceil(460 * S);
  const px = (e) => (e + 320) * S;
  const py = (n) => (240 - n) * S;
  const zoneColor = { airspace: "#B7DBFF", water: "#7BD9C6", land: "#B65B41" };
  let s = [];
  s.push(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" font-family="monospace">`);
  s.push(`<rect width="${W}" height="${H}" fill="#F5F3EC"/>`);
  // water
  s.push(`<rect x="${px(-300)}" y="${py(40)}" width="${600 * S}" height="${240 * S}" fill="#9DC9C2"/>`);
  // land
  s.push(`<rect x="${px(-300)}" y="${py(240)}" width="${600 * S}" height="${200 * S}" fill="#E7E2D2"/>`);
  // roads
  s.push(`<rect x="${px(-260)}" y="${py(170)}" width="${520 * S}" height="${20 * S}" fill="#3B3B3A"/>`);
  s.push(`<rect x="${px(-150)}" y="${py(150)}" width="${20 * S}" height="${106 * S}" fill="#3B3B3A"/>`);
  s.push(`<rect x="${px(-150)}" y="${py(60)}" width="${190 * S}" height="${16 * S}" fill="#3B3B3A"/>`);
  // yard area hint
  s.push(`<rect x="${px(-210)}" y="${py(150)}" width="${110 * S}" height="${90 * S}" fill="#D8D2C0"/>`);
  // warehouses
  s.push(`<rect x="${px(-160)}" y="${py(210)}" width="${100 * S}" height="${40 * S}" fill="#A8A296" stroke="#536D6C"/>`);
  s.push(`<rect x="${px(-40)}" y="${py(210)}" width="${100 * S}" height="${40 * S}" fill="#A8A296" stroke="#AE413D" stroke-dasharray="6 4"/>`);
  s.push(`<rect x="${px(80)}" y="${py(210)}" width="${100 * S}" height="${40 * S}" fill="#A8A296" stroke="#536D6C"/>`);
  // piers
  const pierR = (cx, w, y0, y1, dashed) =>
    s.push(`<rect x="${px(cx - w / 2)}" y="${py(y0)}" width="${w * S}" height="${(y0 - y1) * S}" fill="#B9B4A5" stroke="#536D6C"${dashed ? ' stroke-dasharray="7 5"' : ""}/>`);
  pierR(-140, 14, 40, -80, false);
  pierR(0, 18, 40, -100, false);
  pierR(120, 12, 40, -30, false);
  pierR(120, 12, -30, -60, true); // collapsed remainder
  // crane
  s.push(`<rect x="${px(-9)}" y="${py(-64)}" width="${18 * S}" height="${22 * S}" fill="none" stroke="#B65B41" stroke-width="2"/>`);
  s.push(`<line x1="${px(0)}" y1="${py(-86)}" x2="${px(0)}" y2="${py(-128)}" stroke="#B65B41" stroke-width="3"/>`);
  // sunken obstructions
  for (const [ox, oy] of [[150, -70], [165, -85], [138, -98], [205, -95], [123, -57]]) {
    s.push(`<circle cx="${px(ox)}" cy="${py(oy)}" r="6" fill="#AE413D"/>`);
  }
  // zones (dashed)
  for (const z of WORLD.zones) {
    const [x0, y0] = z.box_enu_m.min, [x1, y1] = z.box_enu_m.max;
    const col = zoneColor[z.kind] || "#536D6C";
    s.push(`<rect x="${px(x0)}" y="${py(y1)}" width="${(x1 - x0) * S}" height="${(y1 - y0) * S}" fill="none" stroke="${col}" stroke-width="2" stroke-dasharray="10 6" opacity="0.9"/>`);
    s.push(`<text x="${px(x0) + 6}" y="${py(y1) + 16}" font-size="12" fill="${col}">${z.id}</text>`);
  }
  // anchors
  for (const a of WORLD.anchors) {
    s.push(`<circle cx="${px(a.position_enu_m[0])}" cy="${py(a.position_enu_m[1])}" r="4" fill="#193B3B"/>`);
    s.push(`<text x="${px(a.position_enu_m[0]) + 7}" y="${py(a.position_enu_m[1]) - 6}" font-size="11" fill="#193B3B">${a.id}</text>`);
  }
  // north arrow + scale bar
  s.push(`<text x="${W - 60}" y="30" font-size="16" fill="#193B3B">N ^</text>`);
  s.push(`<line x1="30" y1="${H - 30}" x2="${30 + 100 * S}" y2="${H - 30}" stroke="#193B3B" stroke-width="2"/>`);
  s.push(`<text x="30" y="${H - 38}" font-size="12" fill="#193B3B">100 m</text>`);
  s.push(`<text x="30" y="26" font-size="13" fill="#536D6C">PORT-001 Kerameion Basin - generated plan view (ENU, north up)</text>`);
  s.push(`</svg>`);
  return s.join("\n");
}

